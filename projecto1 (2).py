# Programa simples: lista de tarefas

tarefas = []

def adicionar(tarefa):
    tarefas.append(tarefa)
    print(f"Tarefa adicionada: {tarefa}")

def listar():
    if not tarefas:
        print("Nenhuma tarefa.")
        return
    print("\nSuas tarefas:")
    for i, t in enumerate(tarefas, start=1):
        print(f"{i}. {t}")

def remover(posicao):
    if 1 <= posicao <= len(tarefas):
        removida = tarefas.pop(posicao - 1)
        print(f"Tarefa removida: {removida}")
    else:
        print("Posição inválida.")

adicionar("Estudar JavaFX")
adicionar("Fazer exportação do banco")
adicionar("Enviar projeto para o GitHub")
listar()

